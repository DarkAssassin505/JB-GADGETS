-- =====================================================================
-- JB Gadgets Store - who is visiting the website
-- =====================================================================
-- The website had nothing counting visitors, so there was no way to say
-- whether it brings anyone in. This counts two things:
--
--   a visit   - somebody opened the site, counted once per browser per
--               day, so reloading all afternoon still counts as one
--               person.
--   an enquiry - somebody used a WhatsApp button, with the phone they
--               were asking about, counted once per phone per browser
--               per day.
--
-- The enquiry figure is the one that matters. Visits say the site is
-- being found; enquiries say it is working.
--
-- Whose numbers these are: the platform owner's. The website belongs to
-- the platform, not to the shop, so these figures are readable by the
-- owner alone and nothing about them appears anywhere in the shop's own
-- screens. That can be opened up later by changing one policy.
--
-- What is not kept: no names, no addresses, no accounts, nothing that
-- identifies a person. A visitor is a random number the browser makes up
-- and throws away at midnight, which is also why no cookie notice is
-- needed - there is nothing here to follow anyone with.
--
-- Deliberately untouched by owner_reset_shop. The handover clears the
-- shop's trading records; this is the platform's own record of its
-- website and survives a handover.
-- =====================================================================


-- ---------------------------------------------------------------------
-- 1. The events
-- ---------------------------------------------------------------------
create table if not exists public.site_events (
    id       bigint generated by default as identity primary key,
    at       timestamptz not null default now(),
    day      date not null default ((now() at time zone 'Africa/Lusaka')::date),
    kind     text not null check (kind in ('visit', 'enquiry')),
    visitor  text not null,
    detail   text,
    device   text,
    referrer text
);

comment on column public.site_events.visitor is
    'A random number the browser invents for the day and then forgets. '
    'Not an account, not a person, and useless for following anyone.';
comment on column public.site_events.detail is
    'For an enquiry, the phone being asked about. For a visit, nothing.';

create index if not exists site_events_day_idx  on public.site_events (day desc, kind);
create index if not exists site_events_at_idx   on public.site_events (at desc);

-- The function below checks how busy one browser has been before it
-- writes, and that check runs on every single page view, so it gets an
-- index of its own rather than reading the whole table each time.
create index if not exists site_events_visitor_idx on public.site_events (visitor, at desc);

-- One row per browser per day per kind - and per phone, for enquiries.
-- This is what stops a reload, or a thumb resting on a button, from
-- turning one person into twenty.
create unique index if not exists site_events_once
    on public.site_events (day, kind, visitor, (coalesce(detail, '')));

alter table public.site_events enable row level security;

-- The owner reads it. Nobody else, Joseph included.
drop policy if exists owner_read on public.site_events;
create policy owner_read on public.site_events
    for select to authenticated using (public.is_owner());

-- A policy only filters rows for someone who may touch the table at all,
-- so the privileges are set out here rather than left to a default:
-- signed-in people may read, and the policy above then narrows that to
-- the owner. Nobody writes directly, and a stranger holding the public
-- key gets nothing - they go through the function below, which can add a
-- row and can never read one back.
revoke all    on public.site_events from anon, authenticated;
grant  select on public.site_events to   authenticated;


-- ---------------------------------------------------------------------
-- 2. What the website calls
-- ---------------------------------------------------------------------
-- Callable with no login, because the website has no login. It takes a
-- row and returns nothing at all, so holding the public key gets a
-- stranger no closer to reading the figures.

create or replace function public.record_site_event(
    p_kind     text,
    p_visitor  text,
    p_detail   text default null,
    p_device   text default null,
    p_referrer text default null
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
    v_recent integer;
begin
    -- Quietly ignore anything malformed. A website visitor must never
    -- see an error from this; it is counting, not trading.
    if p_kind is null or p_kind not in ('visit', 'enquiry') then
        return;
    end if;
    if coalesce(btrim(p_visitor), '') = '' or length(p_visitor) > 64 then
        return;
    end if;

    -- A lid on noise. Forty events from one browser in an hour is well
    -- past anything a real shopper does.
    select count(*) into v_recent
    from public.site_events
    where visitor = p_visitor and at > now() - interval '1 hour';

    if v_recent >= 40 then
        return;
    end if;

    insert into public.site_events (kind, visitor, detail, device, referrer)
    values (p_kind,
            btrim(p_visitor),
            left(nullif(btrim(p_detail), ''), 120),
            left(nullif(btrim(p_device), ''), 20),
            left(nullif(btrim(p_referrer), ''), 120))
    on conflict do nothing;

    -- Two years is plenty, and keeps this from growing forever on its
    -- own. Rarely, so it costs nothing on an ordinary visit.
    if random() < 0.001 then
        delete from public.site_events where at < now() - interval '2 years';
    end if;
end;
$$;

revoke execute on function public.record_site_event(text, text, text, text, text) from public;
grant  execute on function public.record_site_event(text, text, text, text, text) to anon, authenticated;


-- ---------------------------------------------------------------------
-- 3. What the owner reads
-- ---------------------------------------------------------------------
-- One call returns the whole screen: the totals, a day-by-day series
-- with no gaps so the chart is honest about quiet days, and the three
-- breakdowns worth having.

create or replace function public.owner_site_stats(p_days integer default 30)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
    v_today date := (now() at time zone 'Africa/Lusaka')::date;
    v_from  date;
    v_out   jsonb;
begin
    if not public.is_owner() then
        raise exception 'Not allowed: the website figures are the platform owner''s.';
    end if;

    p_days := greatest(1, least(coalesce(p_days, 30), 365));
    v_from := v_today - (p_days - 1);

    select jsonb_build_object(
        'days',      p_days,
        'from',      v_from,
        'to',        v_today,
        'first_day', (select min(day) from public.site_events),

        'today',     (select count(*) from public.site_events
                       where kind = 'visit' and day = v_today),
        'visitors',  (select count(*) from public.site_events
                       where kind = 'visit' and day >= v_from),
        'enquiries', (select count(*) from public.site_events
                       where kind = 'enquiry' and day >= v_from),
        'all_time',  (select count(*) from public.site_events where kind = 'visit'),

        -- Every day in the window, including the empty ones.
        'daily', (
            select coalesce(jsonb_agg(item order by item ->> 'day'), '[]'::jsonb)
            from (
                select jsonb_build_object(
                    'day', g::date,
                    'visits', (select count(*) from public.site_events e
                                where e.kind = 'visit' and e.day = g::date),
                    'enquiries', (select count(*) from public.site_events e
                                   where e.kind = 'enquiry' and e.day = g::date)
                ) as item
                from generate_series(v_from::timestamp, v_today::timestamp, interval '1 day') g
            ) s
        ),

        'devices', (
            select coalesce(jsonb_agg(jsonb_build_object('name', label, 'n', hits)
                                      order by hits desc), '[]'::jsonb)
            from (
                select coalesce(nullif(device, ''), 'unknown') as label, count(*) as hits
                from public.site_events
                where kind = 'visit' and day >= v_from
                group by 1 order by hits desc limit 6
            ) d
        ),

        -- Where they came from. No referrer means they typed the address
        -- or followed a WhatsApp or SMS link, which is worth seeing on
        -- its own rather than lumped in with "unknown".
        'referrers', (
            select coalesce(jsonb_agg(jsonb_build_object('name', label, 'n', hits)
                                      order by hits desc), '[]'::jsonb)
            from (
                select coalesce(nullif(referrer, ''), 'typed in or a direct link') as label,
                       count(*) as hits
                from public.site_events
                where kind = 'visit' and day >= v_from
                group by 1 order by hits desc limit 6
            ) r
        ),

        -- What they asked about, which is the list to buy more of.
        'phones', (
            select coalesce(jsonb_agg(jsonb_build_object('name', label, 'n', hits)
                                      order by hits desc), '[]'::jsonb)
            from (
                select coalesce(nullif(detail, ''), 'general enquiry') as label, count(*) as hits
                from public.site_events
                where kind = 'enquiry' and day >= v_from
                group by 1 order by hits desc limit 8
            ) p
        )
    ) into v_out;

    return v_out;
end;
$$;

revoke execute on function public.owner_site_stats(integer) from public, anon;
grant  execute on function public.owner_site_stats(integer) to authenticated;
