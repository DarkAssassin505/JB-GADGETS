create or replace function public.audit_settings_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
    v_fields text[];
    v_diff   jsonb;
begin
    v_fields := array(select jsonb_object_keys(to_jsonb(new)));
    v_diff := public.audit_diff(to_jsonb(old), to_jsonb(new), v_fields);
    v_diff := v_diff - 'updated_at';
    if v_diff <> '{}'::jsonb then
        perform public.audit('settings changed', tg_table_name, null, null, v_diff);
    end if;
    return new;
end;
$$;

drop trigger if exists audit_change on public.settings;
create trigger audit_change after update on public.settings
    for each row execute function public.audit_settings_change();

drop trigger if exists audit_change on public.receipt_design;
create trigger audit_change after update on public.receipt_design
    for each row execute function public.audit_settings_change();

drop trigger if exists audit_change on public.owner_settings;
create trigger audit_change after update on public.owner_settings
    for each row execute function public.audit_settings_change();


create or replace function public.audit_profile_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
    v_diff jsonb;
begin
    v_diff := public.audit_diff(to_jsonb(old), to_jsonb(new),
                                array['role', 'is_active', 'full_name', 'staff_id']);
    if v_diff <> '{}'::jsonb then
        perform public.audit('staff changed', 'staff', new.id::text, new.full_name, v_diff);
    end if;
    return new;
end;
$$;

drop trigger if exists audit_change on public.profiles;
create trigger audit_change after update on public.profiles
    for each row execute function public.audit_profile_change();


create or replace function public.audit_agreement_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    if old.status is distinct from new.status then
        perform public.audit('plan ' || new.status, 'hire purchase', new.id::text,
                 new.customer_name,
                 jsonb_build_object('from', old.status, 'to', new.status, 'note', new.note));
    end if;
    return new;
end;
$$;

drop trigger if exists audit_change on public.hp_agreements;
create trigger audit_change after update on public.hp_agreements
    for each row execute function public.audit_agreement_change();


-- Clearing the books is one entry with the count, not one per sale.
create or replace function public.audit_sales_cleared()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    perform public.audit('sales history cleared', 'sales', null, null, null);
    return null;
end;
$$;

drop trigger if exists audit_cleared on public.sales;
create trigger audit_cleared after delete on public.sales
    for each statement execute function public.audit_sales_cleared();


