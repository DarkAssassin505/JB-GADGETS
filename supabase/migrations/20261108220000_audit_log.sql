-- =====================================================================
-- JB Gadgets Store - the audit log
-- =====================================================================
-- Who changed a price, moved stock by hand, wrote off a plan, removed a
-- cashier or edited the settings. Two reasons it exists: if stock ever
-- goes missing, this is the first place to look, and if the owner and
-- the shop ever disagree about what was done, it settles it.
--
-- It is written by the database, not by the app, so nothing recorded
-- here can be skipped by calling the API directly or by editing a row
-- in the Supabase dashboard. Stock changes that come from a sale are
-- left out on purpose: those are already the sales ledger, and logging
-- them again would bury the entries that matter.
--
-- Nobody can write to it, change it or delete from it. Not a cashier,
-- not an admin, not the owner.
-- =====================================================================


create table if not exists public.audit_log (
    id          bigint generated by default as identity primary key,
    at          timestamptz not null default now(),
    actor       uuid references public.profiles (id) on delete set null,
    actor_name  text,
    actor_role  text,
    action      text not null,
    entity      text not null,
    entity_id   text,
    entity_name text,
    detail      jsonb
);

create index if not exists audit_log_at_idx     on public.audit_log (at desc);
create index if not exists audit_log_entity_idx on public.audit_log (entity, at desc);

alter table public.audit_log enable row level security;

drop policy if exists admin_read on public.audit_log;
create policy admin_read on public.audit_log
    for select to authenticated using (public.is_admin());

-- Read only, for everyone. The entries come from the triggers below.
revoke insert, update, delete on public.audit_log from anon, authenticated;


-- ---------------------------------------------------------------------
-- How an entry is written
-- ---------------------------------------------------------------------
create or replace function public.audit(
    p_action text, p_entity text, p_entity_id text,
    p_entity_name text, p_detail jsonb default null)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
    v_name text;
    v_role text;
begin
    select full_name, role into v_name, v_role
    from public.profiles where id = auth.uid();

    insert into public.audit_log (actor, actor_name, actor_role, action,
                                  entity, entity_id, entity_name, detail)
    values (auth.uid(), coalesce(v_name, 'system'), coalesce(v_role, '-'),
            p_action, p_entity, p_entity_id, p_entity_name, p_detail);
end;
$$;

-- Builds {field: {from, to}} for whatever actually changed.
create or replace function public.audit_diff(p_old jsonb, p_new jsonb, p_fields text[])
returns jsonb
language plpgsql
immutable
as $$
declare
    v_out jsonb := '{}'::jsonb;
    f text;
begin
    foreach f in array p_fields loop
        if coalesce(p_old -> f, 'null'::jsonb) is distinct from coalesce(p_new -> f, 'null'::jsonb) then
            v_out := v_out || jsonb_build_object(f, jsonb_build_object('from', p_old -> f, 'to', p_new -> f));
        end if;
    end loop;
    return v_out;
end;
$$;


-- ---------------------------------------------------------------------
-- Stock and prices
-- ---------------------------------------------------------------------
-- The app can no longer write to the stock table directly. It goes
-- through these instead, so every hand-made change is recorded with who
-- made it. Selling still writes to the table from inside record_sale,
-- which runs with its own rights and is not affected.

create or replace function public.admin_save_item(
    p_id        uuid    default null,
    p_name      text    default null,
    p_category  text    default null,
    p_condition text    default null,
    p_cost      numeric default 0,
    p_selling   numeric default 0,
    p_stock     integer default 0,
    p_first     numeric default null,
    p_weekly    numeric default null
)
returns public.inventory
language plpgsql
security definer
set search_path = public
as $$
declare
    v_old public.inventory%rowtype;
    v_new public.inventory%rowtype;
    v_diff jsonb;
begin
    if not public.is_admin() then
        raise exception 'Not allowed: only the owner or an admin can change stock.';
    end if;
    if coalesce(btrim(p_name), '') = '' then
        raise exception 'An item needs a name.';
    end if;

    if p_id is null then
        insert into public.inventory (name, category, condition, cost_price,
                                      selling_price, stock, first_payment, weekly_payment)
        values (btrim(p_name), p_category, p_condition, coalesce(p_cost, 0),
                coalesce(p_selling, 0), coalesce(p_stock, 0), p_first, p_weekly)
        returning * into v_new;

        perform public.audit('item added', 'inventory', v_new.id::text, v_new.name,
                 jsonb_build_object('stock', v_new.stock, 'selling_price', v_new.selling_price));
        return v_new;
    end if;

    select * into v_old from public.inventory where id = p_id for update;
    if not found then
        raise exception 'That item is no longer in the catalogue.';
    end if;

    update public.inventory
    set name = btrim(p_name), category = p_category, condition = p_condition,
        cost_price = coalesce(p_cost, 0), selling_price = coalesce(p_selling, 0),
        stock = coalesce(p_stock, 0), first_payment = p_first, weekly_payment = p_weekly,
        updated_at = now()
    where id = p_id
    returning * into v_new;

    v_diff := public.audit_diff(to_jsonb(v_old), to_jsonb(v_new),
        array['name','category','condition','cost_price','selling_price',
              'stock','first_payment','weekly_payment']);

    if v_diff <> '{}'::jsonb then
        perform public.audit(
            case when v_diff ? 'stock' and (select count(*) from jsonb_object_keys(v_diff)) = 1
                 then 'stock adjusted by hand' else 'item changed' end,
            'inventory', v_new.id::text, v_new.name, v_diff);
    end if;
    return v_new;
end;
$$;


create or replace function public.admin_delete_item(p_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
    v_old public.inventory%rowtype;
begin
    if not public.is_admin() then
        raise exception 'Not allowed: only the owner or an admin can remove stock.';
    end if;
    select * into v_old from public.inventory where id = p_id;
    if not found then return; end if;

    delete from public.inventory where id = p_id;

    perform public.audit('item removed', 'inventory', v_old.id::text, v_old.name,
             jsonb_build_object('stock_at_removal', v_old.stock,
                                'selling_price', v_old.selling_price));
end;
$$;


create or replace function public.admin_import_items(p_rows jsonb)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
    v_row   jsonb;
    v_count integer := 0;
begin
    if not public.is_admin() then
        raise exception 'Not allowed: only the owner or an admin can import stock.';
    end if;

    for v_row in select * from jsonb_array_elements(p_rows)
    loop
        insert into public.inventory (name, category, condition, cost_price,
                                      selling_price, stock, first_payment, weekly_payment)
        values (btrim(v_row ->> 'name'), v_row ->> 'category', v_row ->> 'condition',
                coalesce((v_row ->> 'cost_price')::numeric, 0),
                coalesce((v_row ->> 'selling_price')::numeric, 0),
                coalesce((v_row ->> 'stock')::integer, 0),
                nullif(v_row ->> 'first_payment', '')::numeric,
                nullif(v_row ->> 'weekly_payment', '')::numeric);
        v_count := v_count + 1;
    end loop;

    perform public.audit('stock imported', 'inventory', null, null,
             jsonb_build_object('items', v_count));
    return v_count;
end;
$$;

-- With these in place the app has no business writing to the table.
revoke insert, update, delete on public.inventory from anon, authenticated;

revoke execute on function public.admin_save_item(uuid, text, text, text, numeric, numeric, integer, numeric, numeric) from public, anon;
grant  execute on function public.admin_save_item(uuid, text, text, text, numeric, numeric, integer, numeric, numeric) to authenticated;
revoke execute on function public.admin_delete_item(uuid)   from public, anon;
grant  execute on function public.admin_delete_item(uuid)   to authenticated;
revoke execute on function public.admin_import_items(jsonb) from public, anon;
grant  execute on function public.admin_import_items(jsonb) to authenticated;
revoke execute on function public.audit(text, text, text, text, jsonb) from public, anon;
revoke execute on function public.audit_diff(jsonb, jsonb, text[])     from public, anon;


