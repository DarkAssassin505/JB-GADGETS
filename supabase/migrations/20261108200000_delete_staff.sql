-- =====================================================================
-- JB Gadgets Store - removing someone from the team
-- =====================================================================
-- Switching an account off stops it signing in, but the row stays.
-- Deleting it properly has to be safe for the books: a sale, a return,
-- a repair, a plan and a payment all record who handled them, and none
-- of those should disappear because the person has left.
--
-- Every reference to a staff member is changed to leave the record in
-- place and simply forget who it was. Without this, deleting anyone who
-- had ever served a customer would fail outright on a foreign key.
-- =====================================================================

do $$
declare
    r record;
begin
    for r in
        select c.conname,
               n.nspname  as schema_name,
               t.relname  as table_name,
               a.attname  as column_name
        from pg_constraint c
        join pg_class      t on t.oid = c.conrelid
        join pg_namespace  n on n.oid = t.relnamespace
        join pg_class      f on f.oid = c.confrelid
        join pg_attribute  a on a.attrelid = t.oid and a.attnum = c.conkey[1]
        where c.contype   = 'f'
          and n.nspname   = 'public'
          and f.relname   = 'profiles'
          and c.confdeltype <> 'n'          -- 'n' is already SET NULL
          and array_length(c.conkey, 1) = 1
    loop
        -- The column has to accept null for SET NULL to be legal.
        execute format('alter table %I.%I alter column %I drop not null',
                       r.schema_name, r.table_name, r.column_name);
        execute format('alter table %I.%I drop constraint %I',
                       r.schema_name, r.table_name, r.conname);
        execute format('alter table %I.%I add constraint %I foreign key (%I) '
                       || 'references public.profiles (id) on delete set null',
                       r.schema_name, r.table_name, r.conname, r.column_name);
        raise notice 'relaxed %.% (%)', r.table_name, r.column_name, r.conname;
    end loop;
end
$$;


-- ---------------------------------------------------------------------
-- A record of who has left
-- ---------------------------------------------------------------------
-- The profile row goes with the login, so without this there would be
-- nothing left to say the person ever existed. Sales keep pointing at
-- nobody, which is correct, and this is here for the owner to look back
-- on. Only the owner can read it.

create table if not exists public.staff_removed (
    id          bigint generated by default as identity primary key,
    full_name   text not null,
    role        text not null,
    staff_id    text,
    email       text,
    removed_by  uuid references public.profiles (id) on delete set null,
    removed_at  timestamptz not null default now()
);

alter table public.staff_removed enable row level security;

drop policy if exists owner_read on public.staff_removed;
create policy owner_read on public.staff_removed
    for select to authenticated using (public.is_owner());

revoke insert, update, delete on public.staff_removed from anon, authenticated;


-- ---------------------------------------------------------------------
-- The check the server runs before deleting
-- ---------------------------------------------------------------------
-- The deletion itself needs the service role key and happens in the
-- edge function. This decides whether it is allowed, and writes the
-- note above, so the rules live with the data rather than in the
-- function alone.

create or replace function public.admin_prepare_staff_deletion(p_user_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    v_target public.profiles%rowtype;
    v_email  text;
begin
    if not public.is_admin() then
        raise exception 'Not allowed: only the owner or an admin can remove an account.';
    end if;
    if p_user_id = auth.uid() then
        raise exception 'You cannot remove your own account.';
    end if;

    select * into v_target from public.profiles where id = p_user_id;
    if not found then
        raise exception 'That person is not on the staff list.';
    end if;

    -- The owner is not removable by anyone, himself included. There is
    -- only ever one, and losing it would leave the shop with no owner.
    if v_target.role = 'owner' then
        raise exception 'That account cannot be removed.';
    end if;

    select u.email into v_email from auth.users u where u.id = p_user_id;

    insert into public.staff_removed (full_name, role, staff_id, email, removed_by)
    values (v_target.full_name, v_target.role, v_target.staff_id, v_email, auth.uid());

    return jsonb_build_object('ok', true, 'full_name', v_target.full_name,
                              'role', v_target.role, 'staff_id', v_target.staff_id);
end;
$$;

revoke execute on function public.admin_prepare_staff_deletion(uuid) from public, anon;
grant  execute on function public.admin_prepare_staff_deletion(uuid) to authenticated;
