-- =====================================================================
-- JB Gadgets Store - hire purchase
-- =====================================================================
-- Until now the app could only ring up a cash sale. This adds the
-- weekly plans the shop actually sells on:
--
--   1. Each phone carries its own first payment and weekly amount,
--      taken from the price list, so nothing is worked out at the till.
--   2. Selling on hire purchase takes the deposit, moves the phone off
--      the shelf and opens a 12-week agreement in one step.
--   3. Each weekly payment is recorded against that agreement, and the
--      book shows what is still owed and who has fallen behind.
--
-- Money is recorded as it is actually received. The sale banks the
-- deposit that came over the counter; the rest arrives week by week as
-- payments. So takings for a day are the day's sales plus the day's
-- hire purchase payments, and the balance of the book is what is still
-- out there. Cost prices stay where they were - on sale_items, visible
-- to an admin only - so profit on the goods is unaffected.
-- =====================================================================


-- ---------------------------------------------------------------------
-- 1. The plan lives on the phone
-- ---------------------------------------------------------------------
-- Both null means the item is cash only, which is right for most
-- accessories. Both set means it can go out on a plan.

alter table public.inventory
    add column if not exists first_payment  numeric(12,2) check (first_payment  >= 0),
    add column if not exists weekly_payment numeric(12,2) check (weekly_payment >= 0);

alter table public.inventory drop constraint if exists inventory_hp_pair;
alter table public.inventory add constraint inventory_hp_pair check (
    (first_payment is null and weekly_payment is null)
    or (first_payment is not null and weekly_payment is not null and weekly_payment > 0)
);

-- The catalogue a cashier reads. Still no cost column.
create or replace view public.inventory_for_sale as
    select id, name, category, condition, selling_price, stock,
           first_payment, weekly_payment
    from public.inventory
    where public.is_staff();


-- ---------------------------------------------------------------------
-- 2. A sale may now be a hire purchase
-- ---------------------------------------------------------------------
alter table public.sales drop constraint if exists sales_sale_type_check;
alter table public.sales add constraint sales_sale_type_check
    check (sale_type in ('Cash', 'Swap', 'Hire Purchase'));


-- ---------------------------------------------------------------------
-- 3. The agreements and the payments against them
-- ---------------------------------------------------------------------
create table if not exists public.hp_agreements (
    id             bigint generated by default as identity (start with 5001) primary key,
    sale_id        bigint not null references public.sales (id) on delete cascade,
    customer_name  text   not null,
    customer_phone text,
    customer_nrc   text,
    cash_price     numeric(12,2) not null check (cash_price     >= 0),
    deposit        numeric(12,2) not null check (deposit        >= 0),
    weekly_payment numeric(12,2) not null check (weekly_payment >  0),
    weeks          integer       not null default 12 check (weeks between 1 and 52),
    total_payable  numeric(12,2) not null check (total_payable  >= 0),
    started_on     date   not null default current_date,
    status         text   not null default 'active'
                   check (status in ('active', 'settled', 'written off')),
    note           text,
    opened_by      uuid references public.profiles (id),
    created_at     timestamptz not null default now(),
    updated_at     timestamptz not null default now()
);

-- One agreement per sale.
create unique index if not exists hp_agreements_sale_key
    on public.hp_agreements (sale_id);
create index if not exists hp_agreements_status_idx
    on public.hp_agreements (status);

create table if not exists public.hp_payments (
    id           bigint generated by default as identity (start with 9001) primary key,
    agreement_id bigint not null references public.hp_agreements (id) on delete cascade,
    amount       numeric(12,2) not null check (amount > 0),
    paid_on      date   not null default current_date,
    method       text   not null default 'Cash'
                 check (method in ('Cash', 'Airtel Money', 'MTN MoMo', 'Bank', 'Other')),
    note         text,
    received_by  uuid references public.profiles (id),
    client_ref   uuid,
    created_at   timestamptz not null default now()
);

create index if not exists hp_payments_agreement_idx
    on public.hp_payments (agreement_id);

-- Same guard as on sales: a payment taken while the line was down and
-- sent twice is banked once.
create unique index if not exists hp_payments_client_ref_key
    on public.hp_payments (client_ref) where client_ref is not null;


-- ---------------------------------------------------------------------
-- 4. The book
-- ---------------------------------------------------------------------
-- What is owed, what has come in, and who is behind. "Behind" compares
-- what should have been paid by today against what has been, so a
-- customer who pays ahead shows no arrears.

create or replace view public.hp_book as
select x.*,
       greatest(x.expected_to_date - x.paid_to_date, 0) as arrears
from (
    select a.id,
           a.sale_id,
           a.customer_name,
           a.customer_phone,
           a.customer_nrc,
           a.cash_price,
           a.deposit,
           a.weekly_payment,
           a.weeks,
           a.total_payable,
           a.total_payable - a.cash_price                        as credit_charge,
           a.started_on,
           a.started_on + (a.weeks * 7)                          as final_due_on,
           a.status,
           a.note,
           w.elapsed                                             as weeks_elapsed,
           coalesce(p.paid, 0)                                   as instalments_paid,
           a.deposit + coalesce(p.paid, 0)                       as paid_to_date,
           a.total_payable - a.deposit - coalesce(p.paid, 0)     as balance,
           a.deposit + (a.weekly_payment * w.elapsed)            as expected_to_date,
           p.last_paid                                           as last_payment_on,
           p.payment_count
    from public.hp_agreements a
    left join (
        select agreement_id,
               sum(amount)   as paid,
               max(paid_on)  as last_paid,
               count(*)      as payment_count
        from public.hp_payments
        group by agreement_id
    ) p on p.agreement_id = a.id
    cross join lateral (
        select least(greatest(floor((current_date - a.started_on) / 7.0), 0), a.weeks)::int
    ) as w(elapsed)
) x
where public.is_staff();


-- ---------------------------------------------------------------------
-- 5. Selling on a plan
-- ---------------------------------------------------------------------
-- Takes the deposit, moves the stock and opens the agreement together,
-- so a phone can never leave the shelf without a plan behind it.

create or replace function public.record_hire_purchase(
    p_items          jsonb,
    p_customer_name  text,
    p_customer_phone text    default null,
    p_customer_nrc   text    default null,
    p_deposit        numeric default null,
    p_weekly         numeric default null,
    p_weeks          integer default 12,
    p_client_ref     uuid    default null
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
    v_sale_id      bigint;
    v_agreement_id bigint;
    v_item         jsonb;
    v_row          public.inventory%rowtype;
    v_qty          integer;
    v_cash         numeric(12,2) := 0;
    v_deposit      numeric(12,2) := 0;
    v_weekly       numeric(12,2) := 0;
begin
    if not public.is_staff() then
        raise exception 'Not allowed: you are not signed in as staff.';
    end if;
    if p_items is null or jsonb_array_length(p_items) = 0 then
        raise exception 'A hire purchase needs at least one item.';
    end if;
    if coalesce(btrim(p_customer_name), '') = '' then
        raise exception 'A hire purchase needs the customer''s name.';
    end if;
    if p_weeks is null or p_weeks < 1 or p_weeks > 52 then
        raise exception 'The plan must run between 1 and 52 weeks.';
    end if;

    -- Already banked under this reference? Hand back the original.
    if p_client_ref is not null then
        select a.id into v_agreement_id
        from public.hp_agreements a
        join public.sales s on s.id = a.sale_id
        where s.client_ref = p_client_ref;
        if found then
            return v_agreement_id;
        end if;
    end if;

    insert into public.sales (customer_name, sale_type, sold_by, client_ref)
    values (btrim(p_customer_name), 'Hire Purchase', auth.uid(), p_client_ref)
    returning id into v_sale_id;

    for v_item in select * from jsonb_array_elements(p_items)
    loop
        v_qty := (v_item ->> 'qty')::integer;
        if v_qty is null or v_qty < 1 then
            raise exception 'Every line needs a quantity of at least one.';
        end if;

        select * into v_row from public.inventory
        where id = (v_item ->> 'inventory_id')::uuid
        for update;

        if not found then
            raise exception 'That product is no longer in the catalogue.';
        end if;
        if v_row.stock < v_qty then
            raise exception 'Only % left of %, cannot sell %.', v_row.stock, v_row.name, v_qty;
        end if;
        if v_row.first_payment is null or v_row.weekly_payment is null then
            raise exception '% is cash only. Set its first payment and weekly amount to sell it on a plan.', v_row.name;
        end if;

        update public.inventory
        set stock = stock - v_qty, updated_at = now()
        where id = v_row.id;

        insert into public.sale_items (sale_id, inventory_id, name, category, condition,
                                       cost_price, selling_price, qty)
        values (v_sale_id, v_row.id, v_row.name, v_row.category, v_row.condition,
                v_row.cost_price, v_row.selling_price, v_qty);

        v_cash    := v_cash    + (v_row.selling_price * v_qty);
        v_deposit := v_deposit + (v_row.first_payment  * v_qty);
        v_weekly  := v_weekly  + (v_row.weekly_payment * v_qty);
    end loop;

    -- The till may agree a different deposit or weekly figure; the
    -- price list is only the starting point.
    v_deposit := coalesce(p_deposit, v_deposit);
    v_weekly  := coalesce(p_weekly,  v_weekly);

    if v_weekly <= 0 then
        raise exception 'The weekly payment must be more than zero.';
    end if;
    if v_deposit < 0 then
        raise exception 'The first payment cannot be negative.';
    end if;

    -- subtotal is the cash value of the goods; total is the money that
    -- actually came over the counter today.
    update public.sales
    set subtotal = v_cash, total = v_deposit
    where id = v_sale_id;

    insert into public.hp_agreements (
        sale_id, customer_name, customer_phone, customer_nrc,
        cash_price, deposit, weekly_payment, weeks, total_payable, opened_by)
    values (
        v_sale_id, btrim(p_customer_name), nullif(btrim(p_customer_phone), ''),
        nullif(btrim(p_customer_nrc), ''),
        v_cash, v_deposit, v_weekly, p_weeks,
        v_deposit + (v_weekly * p_weeks), auth.uid())
    returning id into v_agreement_id;

    return v_agreement_id;
end;
$$;


-- ---------------------------------------------------------------------
-- 6. Taking a weekly payment
-- ---------------------------------------------------------------------
create or replace function public.record_hp_payment(
    p_agreement_id bigint,
    p_amount       numeric,
    p_method       text default 'Cash',
    p_paid_on      date default null,
    p_note         text default null,
    p_client_ref   uuid default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    v_agreement public.hp_agreements%rowtype;
    v_paid      numeric(12,2);
    v_balance   numeric(12,2);
    v_payment   bigint;
begin
    if not public.is_staff() then
        raise exception 'Not allowed: you are not signed in as staff.';
    end if;
    if p_amount is null or p_amount <= 0 then
        raise exception 'A payment must be more than zero.';
    end if;

    if p_client_ref is not null then
        select id into v_payment from public.hp_payments where client_ref = p_client_ref;
        if found then
            select a.* into v_agreement from public.hp_agreements a
            where a.id = (select agreement_id from public.hp_payments where id = v_payment);
            select coalesce(sum(amount), 0) into v_paid
            from public.hp_payments where agreement_id = v_agreement.id;
            return jsonb_build_object('payment_id', v_payment, 'repeat', true,
                                      'balance', v_agreement.total_payable - v_agreement.deposit - v_paid,
                                      'status', v_agreement.status);
        end if;
    end if;

    select * into v_agreement from public.hp_agreements
    where id = p_agreement_id
    for update;

    if not found then
        raise exception 'That agreement does not exist.';
    end if;
    if v_agreement.status <> 'active' then
        raise exception 'That agreement is already marked %.', v_agreement.status;
    end if;

    select coalesce(sum(amount), 0) into v_paid
    from public.hp_payments where agreement_id = v_agreement.id;

    v_balance := v_agreement.total_payable - v_agreement.deposit - v_paid;

    if p_amount > v_balance then
        raise exception 'That is more than is owed. The balance is K%.', trim(to_char(v_balance, '999999990.99'));
    end if;

    insert into public.hp_payments (agreement_id, amount, paid_on, method, note, received_by, client_ref)
    values (v_agreement.id, p_amount, coalesce(p_paid_on, current_date),
            coalesce(nullif(btrim(p_method), ''), 'Cash'),
            nullif(btrim(p_note), ''), auth.uid(), p_client_ref)
    returning id into v_payment;

    v_balance := v_balance - p_amount;

    if v_balance <= 0 then
        update public.hp_agreements
        set status = 'settled', updated_at = now()
        where id = v_agreement.id;
    else
        update public.hp_agreements set updated_at = now() where id = v_agreement.id;
    end if;

    return jsonb_build_object('payment_id', v_payment, 'repeat', false,
                              'balance', v_balance,
                              'status', case when v_balance <= 0 then 'settled' else 'active' end);
end;
$$;


-- ---------------------------------------------------------------------
-- 7. Closing an agreement that will not be paid
-- ---------------------------------------------------------------------
-- Writing off is a decision with money attached, so it is owner and
-- admin only, and it always needs a reason.

create or replace function public.write_off_hp_agreement(
    p_agreement_id bigint,
    p_reason       text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    v_agreement public.hp_agreements%rowtype;
    v_paid      numeric(12,2);
begin
    if not public.is_admin() then
        raise exception 'Not allowed: only the owner or an admin can write off an agreement.';
    end if;
    if coalesce(btrim(p_reason), '') = '' then
        raise exception 'Writing off needs a reason.';
    end if;

    select * into v_agreement from public.hp_agreements where id = p_agreement_id for update;
    if not found then
        raise exception 'That agreement does not exist.';
    end if;
    if v_agreement.status <> 'active' then
        raise exception 'That agreement is already marked %.', v_agreement.status;
    end if;

    select coalesce(sum(amount), 0) into v_paid
    from public.hp_payments where agreement_id = v_agreement.id;

    update public.hp_agreements
    set status = 'written off',
        note   = btrim(p_reason),
        updated_at = now()
    where id = v_agreement.id;

    return jsonb_build_object(
        'agreement_id', v_agreement.id,
        'written_off',  v_agreement.total_payable - v_agreement.deposit - v_paid);
end;
$$;


-- ---------------------------------------------------------------------
-- 8. A hire purchase is not returned over the counter
-- ---------------------------------------------------------------------
-- The existing return puts stock back and reverses the takings, which
-- would leave an agreement pointing at a sale that no longer happened.
-- Those are unwound by writing the agreement off instead.

create or replace function public.process_return(
    p_sale_id bigint,
    p_reason  text default 'Customer Return'
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
    v_sale public.sales%rowtype;
    v_item public.sale_items%rowtype;
begin
    if not public.is_staff() then
        raise exception 'Not allowed: you are not signed in as staff.';
    end if;

    select * into v_sale from public.sales where id = p_sale_id for update;
    if not found then
        raise exception 'Sale % was not found.', p_sale_id;
    end if;
    if v_sale.returned then
        raise exception 'Sale % has already been returned.', p_sale_id;
    end if;

    -- The only line added to this function.
    if v_sale.sale_type = 'Hire Purchase' then
        raise exception 'Sale % is a hire purchase. Write the agreement off instead, which keeps the payments already taken on the books.', p_sale_id;
    end if;

    for v_item in select * from public.sale_items where sale_id = p_sale_id
    loop
        if v_item.inventory_id is not null then
            update public.inventory
            set stock = stock + v_item.qty, updated_at = now()
            where id = v_item.inventory_id;
        end if;
    end loop;

    update public.sales set returned = true where id = p_sale_id;

    insert into public.returns_log (sale_id, reason, refund_total, handled_by)
    values (p_sale_id, coalesce(nullif(p_reason, ''), 'Customer Return'), v_sale.total, auth.uid());
end;
$$;


-- ---------------------------------------------------------------------
-- 9. Clearing practice transactions takes the plans with it
-- ---------------------------------------------------------------------
create or replace function public.clear_sales_history()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    v_sales      integer;
    v_returns    integer;
    v_agreements integer;
    v_units      integer;
begin
    if not public.is_admin() then
        raise exception 'Not allowed: only the owner or an admin can clear sales history.';
    end if;

    select count(*) into v_sales      from public.sales;
    select count(*) into v_returns    from public.returns_log;
    select count(*) into v_agreements from public.hp_agreements;

    select coalesce(sum(si.qty), 0) into v_units
    from public.sale_items si
    join public.sales s on s.id = si.sale_id
    where not s.returned;

    -- A sale already marked returned had its stock restored at the time.
    update public.inventory i
    set stock = i.stock + x.qty, updated_at = now()
    from (
        select si.inventory_id, sum(si.qty) as qty
        from public.sale_items si
        join public.sales s on s.id = si.sale_id
        where not s.returned and si.inventory_id is not null
        group by si.inventory_id
    ) x
    where i.id = x.inventory_id;

    delete from public.hp_payments;
    delete from public.hp_agreements;
    delete from public.returns_log;
    delete from public.sale_items;
    delete from public.sales;

    return jsonb_build_object('sales', v_sales, 'returns', v_returns,
                              'agreements', v_agreements, 'units_restored', v_units);
end;
$$;


-- ---------------------------------------------------------------------
-- 10. Who may do what
-- ---------------------------------------------------------------------
alter table public.hp_agreements enable row level security;
alter table public.hp_payments   enable row level security;

drop policy if exists staff_read on public.hp_agreements;
drop policy if exists staff_read on public.hp_payments;

-- Staff read the book; nobody writes to these tables directly.
create policy staff_read on public.hp_agreements
    for select to authenticated using (public.is_staff());
create policy staff_read on public.hp_payments
    for select to authenticated using (public.is_staff());

revoke insert, update, delete on public.hp_agreements, public.hp_payments
    from anon, authenticated;

revoke execute on function public.record_hire_purchase(jsonb, text, text, text, numeric, numeric, integer, uuid) from public, anon;
grant  execute on function public.record_hire_purchase(jsonb, text, text, text, numeric, numeric, integer, uuid) to authenticated;

revoke execute on function public.record_hp_payment(bigint, numeric, text, date, text, uuid) from public, anon;
grant  execute on function public.record_hp_payment(bigint, numeric, text, date, text, uuid) to authenticated;

revoke execute on function public.write_off_hp_agreement(bigint, text) from public, anon;
grant  execute on function public.write_off_hp_agreement(bigint, text) to authenticated;

-- The book is a view, which does not carry the tables' row security of
-- its own accord, so the is_staff() test inside it is what keeps a
-- stranger out. Same for the catalogue above.
revoke all on public.hp_book from public, anon;
grant  select on public.hp_book to authenticated;
revoke all on public.inventory_for_sale from public, anon;
grant  select on public.inventory_for_sale to authenticated;


